-- VoxBridge: anonymous download counters and support messages.
-- Applied to project rlmrgjxvuddexupkobpc. Safe to re-run.

create table if not exists public.download_events (
  id bigint generated by default as identity primary key,
  platform text not null check (platform in ('windows', 'android', 'ios', 'mac', 'other')),
  version text,
  source text default 'website',
  created_at timestamptz not null default now()
);

create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  email text,
  topic text not null default 'general',
  message text not null check (char_length(message) between 2 and 8000),
  platform text,
  app_version text,
  created_at timestamptz not null default now()
);

create index if not exists download_events_created_idx on public.download_events (created_at desc);
create index if not exists download_events_platform_idx on public.download_events (platform);
create index if not exists feedback_created_idx on public.feedback (created_at desc);

alter table public.download_events enable row level security;
alter table public.feedback enable row level security;

drop policy if exists "anon can record downloads" on public.download_events;
create policy "anon can record downloads" on public.download_events
  for insert to anon, authenticated with check (true);

drop policy if exists "anon can send feedback" on public.feedback;
create policy "anon can send feedback" on public.feedback
  for insert to anon, authenticated with check (true);

create or replace function public.download_counts()
returns table (platform text, count bigint)
language sql
security definer
set search_path = public
as $$
  select platform, count(*)::bigint as count
  from public.download_events
  group by platform
  order by platform;
$$;

revoke all on function public.download_counts() from public;
grant execute on function public.download_counts() to anon, authenticated;
grant insert on public.download_events to anon, authenticated;
grant insert on public.feedback to anon, authenticated;
