/**
 * Parsed contents of the QR code the desktop app shows in its Pair view.
 * Accepts `voxbridge://pair?host=..&port=..&code=..` plus the looser
 * `voxbridge://host:port?code=..` and a bare `192.168.1.20:8720` so a code
 * generated by an older build still works.
 */
data class PairPayload(val host: String, val port: Int, val code: String?)

fun parsePairPayload(raw: String): PairPayload? {
    val text = raw.trim()
    if (text.isEmpty()) return null
    var host = ""
    var port = 8720
    var code: String? = null

    if (text.startsWith("voxbridge://", ignoreCase = true)) {
        val rest = text.substring("voxbridge://".length)
        val withoutQuery = rest.substringBefore('?')
        val query = rest.substringAfter('?', "")

        if (withoutQuery.startsWith("pair", ignoreCase = true)) {
            for (part in query.split('&')) {
                val key = part.substringBefore('=', "").lowercase()
                val value = part.substringAfter('=', "")
                when (key) {
                    "host", "address", "ip" -> host = value
                    "port" -> value.toIntOrNull()?.let { port = it }
                    "code", "pin" -> if (value.isNotBlank()) code = value
                }
            }
        } else {
            host = withoutQuery.substringBefore(':')
            withoutQuery.substringAfter(':', "").toIntOrNull()?.let { port = it }
            for (part in query.split('&')) {
                val key = part.substringBefore('=', "").lowercase()
                val value = part.substringAfter('=', "")
                if (key == "code" || key == "pin") {
                    if (value.isNotBlank()) code = value
                }
            }
        }
    } else {
        host = text.substringBefore(':')
        text.substringAfter(':', "").toIntOrNull()?.let { port = it }
    }

    host = host.trim()
    if (host.isEmpty()) return null
    if (port !in 1..65535) port = 8720
    return PairPayload(host, port, code)
}

/**
 * Full-screen camera scanner. Runs ZXing's MultiFormatReader over each analysis
 * frame on a single background thread and reports the first pair payload it
 * recognises. Nothing is written to disk and frames are closed immediately.
 */
@Composable
fun QrScannerOverlay(
    onResult: (PairPayload) -> Unit,
    onCancel: () -> Unit,
) {
    val context = LocalContext.current
    val lifecycleOwner = LocalLifecycleOwner.current
    var granted by remember {
        mutableStateOf(
            ContextCompat.checkSelfPermission(context, Manifest.permission.CAMERA) ==
                PackageManager.PERMISSION_GRANTED
        )
    }
    var status by remember { mutableStateOf("Point the camera at the QR code on your PC") }

    val launcher = rememberLauncherForActivityResult(
        ActivityResultContracts.RequestPermission()
    ) { allowed ->
        granted = allowed
        if (!allowed) status = "Camera permission is needed to scan the code."
    }

    LaunchedEffect(Unit) {
        if (!granted) launcher.launch(Manifest.permission.CAMERA)
    }

    val executor = remember { Executors.newSingleThreadExecutor() }
    val reader = remember {
        MultiFormatReader().apply {
            setHints(
                mapOf(
                    DecodeHintType.POSSIBLE_FORMATS to listOf(BarcodeFormat.QR_CODE),
                    DecodeHintType.TRY_HARDER to true,
                )
            )
        }
    }
    // Touched from the camera analysis thread, so keep it off Compose state.
    val handled = remember { java.util.concurrent.atomic.AtomicBoolean(false) }

    DisposableEffect(Unit) {
        onDispose { executor.shutdown() }
    }

    Box(
        Modifier.fillMaxSize().background(Color(0xF010100E))
    ) {
        if (granted) {
            AndroidView(
                modifier = Modifier.fillMaxSize(),
                factory = { viewContext ->
                    val previewView = PreviewView(viewContext).apply {
                        scaleType = PreviewView.ScaleType.FILL_CENTER
                    }
                    val providerFuture = ProcessCameraProvider.getInstance(viewContext)
                    providerFuture.addListener({
                        val provider = providerFuture.get()
                        val preview = Preview.Builder().build().also {
                            it.setSurfaceProvider(previewView.surfaceProvider)
                        }
                        val analysis = ImageAnalysis.Builder()
                            .setBackpressureStrategy(ImageAnalysis.STRATEGY_KEEP_ONLY_LATEST)
                            .build()
                        analysis.setAnalyzer(executor) { image ->
                            if (!handled.get()) {
                                val raw = decodeFrame(image, reader)
                                if (raw != null) {
                                    val payload = parsePairPayload(raw)
                                    if (payload != null) {
                                        handled.set(true)
                                        viewContext.post { onResult(payload) }
                                    } else {
                                        viewContext.post {
                                            status = "That QR code is not a VoxBridge pairing code."
                                        }
                                    }
                                }
                            }
                            image.close()
                        }
                        try {
                            provider.unbindAll()
                            provider.bindToLifecycle(
                                lifecycleOwner,
                                CameraSelector.DEFAULT_BACK_CAMERA,
                                preview,
                                analysis,
                            )
                        } catch (_: Exception) {
                            viewContext.post {
                                status = "Could not open the camera on this device."
                            }
                        }
                    }, ContextCompat.getMainExecutor(viewContext))
                    previewView
                },
            )
        }

        Column(
            Modifier
                .align(Alignment.BottomCenter)
                .fillMaxWidth()
                .padding(24.dp),
            horizontalAlignment = Alignment.CenterHorizontally,
            verticalArrangement = Arrangement.spacedBy(14.dp),
        ) {
            Text(status, color = Color(0xFFF2EFE7), fontSize = 13.sp, lineHeight = 19.sp)
            Box(
                Modifier
                    .fillMaxWidth()
                    .clip(RoundedCornerShape(14.dp))
                    .background(Color(0xFF1C1C18))
                    .clickable { onCancel() }
                    .padding(vertical = 14.dp),
                contentAlignment = Alignment.Center,
            ) {
                Text("Cancel", color = Color(0xFFF2EFE7), fontSize = 14.sp)
            }
            Text(
                "Open VoxBridge on your PC, choose Pair, and point the camera at the code.",
                color = Color(0xFF8C8A80),
                fontSize = 11.sp,
                lineHeight = 16.sp,
            )
        }
    }
}

private fun decodeFrame(image: ImageProxy, reader: MultiFormatReader): String? {
    return try {
        val plane = image.planes[0]
        val buffer = plane.buffer
        val width = image.width
        val height = image.height
        val rowStride = plane.rowStride
        val pixelStride = plane.pixelStride
        val data = ByteArray(width * height)
        if (pixelStride == 1 && rowStride == width) {
            buffer.get(data, 0, minOf(data.size, buffer.remaining()))
        } else {
            val row = ByteArray(rowStride)
            var offset = 0
            for (y in 0 until height) {
                val remaining = buffer.remaining()
                if (remaining <= 0) break
                val count = minOf(rowStride, remaining)
                buffer.get(row, 0, count)
                for (x in 0 until width) {
                    val index = offset + x
                    if (index < data.size && x * pixelStride < count) {
                        data[index] = row[x * pixelStride]
                    }
                }
                offset += width
            }
        }
        val source = PlanarYUVLuminanceSource(data, width, height, 0, 0, width, height, false)
        val bitmap = BinaryBitmap(HybridBinarizer(source))
        reader.decodeWithState(bitmap).text
    } catch (_: Exception) {
        null
    } finally {
        reader.reset()
    }
}
